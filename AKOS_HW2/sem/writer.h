#ifndef WRITER_H
#define WRITER_H

#include "database.h"

/*
 * Аргументы потока-писателя.
 * Передаются через pthread_create как единственный void* аргумент.
 */
typedef struct {
    int          id;            /* Порядковый номер писателя (1-based) */
    database_t  *db;            /* Указатель на разделяемую базу данных */
    int          num_ops;       /* Кол-во операций (0 = бесконечно, до stop_flag) */
    int          max_val;       /* Максимальное значение нового элемента */
    int          sleep_min_ms;  /* Нижняя граница задержки между операциями (мс) */
    int          sleep_max_ms;  /* Верхняя граница задержки между операциями (мс) */
} writer_args_t;

/*
 * Функция потока писателя.
 * Каждую итерацию:
 *   1. Запрашивает эксклюзивный доступ (db_write_lock).
 *   2. Заменяет случайный элемент новым случайным значением.
 *   3. Восстанавливает сортировку (qsort).
 *   4. Выводит старое, новое значения и текущее состояние массива.
 *   5. Освобождает блокировку (db_write_unlock).
 *   6. Засыпает на случайное время.
 */
void *writer_thread(void *arg);

#endif /* WRITER_H */
