#ifndef READER_H
#define READER_H

#include "database.h"

/*
 * Аргументы потока-читателя.
 * Передаются через pthread_create как единственный void* аргумент.
 */
typedef struct {
    int          id;            /* Порядковый номер читателя (1-based) */
    database_t  *db;            /* Указатель на разделяемую базу данных */
    int          num_ops;       /* Кол-во операций (0 = бесконечно, до stop_flag) */
    int          sleep_min_ms;  /* Нижняя граница задержки между операциями (мс) */
    int          sleep_max_ms;  /* Верхняя граница задержки между операциями (мс) */
} reader_args_t;

/*
 * Функция потока читателя.
 * Каждую итерацию:
 *   1. Запрашивает доступ на чтение (db_read_lock).
 *   2. Читает случайный элемент массива.
 *   3. Освобождает блокировку (db_read_unlock).
 *   4. Вычисляет число Фибоначчи для прочитанного значения.
 *   5. Засыпает на случайное время перед следующей операцией.
 */
void *reader_thread(void *arg);

#endif /* READER_H */
